#!/usr/bin/env python3
"""Stage A, step 3: join the ledger and write ledger/SUMMARY.md (the first reading map).
Everything here is counted from ledger/*.tsv. No model tokens, none of de Lubac's prose."""
import csv, json, collections
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
rd = lambda f: list(csv.DictReader(open(f, encoding="utf-8"), delimiter="\t", quoting=csv.QUOTE_NONE))
R = rd(ROOT / "ledger/refs.tsv"); C = rd(ROOT / "ledger/colonly.tsv"); N = rd(ROOT / "ledger/notes.tsv")
K = {k["id"]: k for k in rd(ROOT / "ledger/quote-check.tsv")}
PG = {}
for t in json.load(open(Path.home() / "patrologia/data/pg-tome-authors.json"))["tomes"]:
    PG.setdefault(int(t["tome"].split("-")[0]), t["author"])        # 007-1 / 007-2: one tome, two parts
TOMES = ["I/1", "I/2", "II/1", "II/2"]
cnt = collections.Counter

def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(head))) + "|"]
    return "\n".join(out + ["| " + " | ".join(str(x) for x in r) + " |" for r in rows])

res = [r for r in R if r["status"].startswith("resolved") and "?" not in r["status"]]
L = ["# De Lubac ledger: what the harvest found", "",
     "Generated by `scripts/summarize.py` from `ledger/*.tsv`. Do not edit by hand; re-run.",
     "Counts are of *references*, not of distinct passages. Method and caveats: `../STUDY.md`.", ""]

L += ["## 1. References harvested", ""]
rows = []
for t in TOMES + ["all"]:
    S = [r for r in R if t == "all" or r["tome"] == t]
    rows.append([t, sum(r["form"] == "explicit" and r["series"] == "PL" for r in S),
                 sum(r["form"] == "bare" and r["series"] == "PL" for r in S),
                 sum(r["series"] == "PG" for r in S), sum(r["series"] not in ("PL", "PG") for r in S),
                 sum(r["form"] == "colonly" for r in S),
                 sum(1 for c in C if (t == "all" or c["tome"] == t) and c["year"] == "0" and c["band"]),
                 sum(1 for c in C if (t == "all" or c["tome"] == t) and c["year"] == "0" and not c["band"])])
L += [table(["tome", "PL with siglum", "PL, siglum dropped", "PG", "bare, other series", "column only, volume carried",
             "residue: column + band, no volume", "residue: bare number, no volume"], rows), "",
      "The last two columns are not in the ledger. A bare number may be a Migne column, a page of the GCS,",
      "CSEL or Sources chrétiennes, or a folio; parenthesised years are already excluded.", ""]

L += ["## 2. How the PL references resolve against the TEI on disk", ""]
st = cnt(r["status"] for r in R if r["series"] == "PL")
L += [table(["status", "refs"], sorted(st.items(), key=lambda x: -x[1])), ""]

L += ["## 3. The quote check (where he prints the passage before the reference)", ""]
rows = []
for form, src in (("explicit", "siglum"), ("bare", "carried"), ("bare", "default"),
                  ("colonly", "carried-note")):
    S = [K[r["id"]]["check"] for r in R if r["id"] in K and r["form"] == form and r["series_src"] == src]
    c = cnt(S); n = len(S) or 1
    rows.append([f"{form} / {src}", len(S), c["at-column"], f"{100 * c['at-column'] / n:.0f}%", c["in-work"], c["absent"]])
L += [table(["form / series from", "checked", "at the column", "share", "same work, other column", "absent"], rows), "",
      f"Resolved PL references with no quote to check: {sum(1 for r in res if r['id'] not in K)}.", ""]

L += ["## 4. Whom he cites: resolved PL references by author (top 40)", "",
      "Author is the Corpus Corporum heading for the work at that volume and column, so pseudonymous",
      "and doubtful works sit under the heading Migne gave them. Year is the death year in that index.", ""]
A = cnt((r["author"], r["author_year"]) for r in res)
tot = len(res)
rows = [[a, y, n, f"{100 * n / tot:.1f}%"] + [sum(1 for r in res if r["author"] == a and r["tome"] == t) for t in TOMES]
        for (a, y), n in A.most_common(40)]
L += [table(["author", "d.", "refs", "share"] + TOMES, rows), "",
      f"Distinct author headings: {len(A)}. Distinct works: {len({r['idno'] for r in res})}. "
      f"Distinct PL volumes: {len({r['vol'] for r in res})} of 217.", ""]

L += ["## 5. By century of the author's death (resolved PL references)", ""]
cen = cnt()
for r in res:
    y = r["author_year"]
    cen[(int(y) - 1) // 100 + 1 if y.lstrip("-").isdigit() and int(y) > 0 else "undated"] += 1
rows = [[c, cen[c], f"{100 * cen[c] / tot:.1f}%"] for c in sorted([c for c in cen if c != "undated"])] + [["undated", cen["undated"], ""]]
L += [table(["century", "refs", "share"], rows), ""]

L += ["## 6. PG references by tome (author at tome level only)", ""]
P = cnt(int(r["vol"]) for r in R if r["series"] == "PG" and r["vol"])
by = cnt()
for v, n in P.items():
    by[PG.get(v, "?")] += n
L += [table(["PG tome author(s)", "refs"], [[a[:90], n] for a, n in by.most_common(20)]), ""]

L += ["## 7. Footnotes by what they carry", ""]
mig = sum(1 for x in N if int(x["n_pl"]) + int(x["n_pg"]) > 0)
co = sum(1 for x in N if int(x["n_pl"]) + int(x["n_pg"]) == 0 and int(x["n_colonly"]) > 0)
rest = [x for x in N if int(x["n_pl"]) + int(x["n_pg"]) + int(x["n_colonly"]) == 0]
oth = sum(1 for x in rest if x["other"])
loc = sum(1 for x in rest if not x["other"] and x["locus"] == "1")
L += [table(["footnotes (approximate: the OCR loses some note numerals)", "count"],
            [["all", len(N)], ["with a Migne reference that names its volume", mig],
             ["with only a bare column or page in parentheses", co],
             ["with another series only (CCL, SC, MGH, CSEL...)", oth],
             ["no series, but an ancient-style locus (l., c., n., h., ep.)", loc],
             ["none of the above (modern literature, cross-references, remarks)", len(rest) - oth - loc]]), ""]
(ROOT / "ledger/SUMMARY.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L))
